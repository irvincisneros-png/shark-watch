// Turns data/*.json into src/data/baked.js so the game ships the real data as a plain ES module (no fetch at runtime).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const stations = JSON.parse(fs.readFileSync(path.join(root, 'data/stations.json'), 'utf8'));
const track = JSON.parse(fs.readFileSync(path.join(root, 'data/real-track.json'), 'utf8'));
fs.writeFileSync(path.join(root, 'src/data/baked.js'),
  `// GENERATED by tools/build-data-module.mjs from data/*.json. Do not edit by hand.\n// Source: IMOS Animal Tracking Database, https://animaltracking.aodn.org.au\nexport const STATIONS_DATA = ${JSON.stringify(stations, null, 1)};\nexport const REAL_TRACK = ${JSON.stringify(track, null, 1)};\n`);
console.log('wrote src/data/baked.js');
